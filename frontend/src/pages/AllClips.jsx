import React, { useEffect, useState } from 'react';
import { 
  Film, 
  Sparkles, 
  Clock, 
  Download, 
  Trash2, 
  CheckSquare, 
  Square, 
  Play, 
  FileText,
  Filter,
  Loader2,
  FolderKanban
} from 'lucide-react';
import { listClips, deleteClip, getClipDownloadUrl, getSubtitleDownloadUrl, listProjects, resolveMediaUrl } from '../services/api';
import ClipPlayerModal from '../components/ClipPlayerModal';

export default function AllClips({ selectedProjectId, setSelectedProjectId }) {
  const [clips, setClips] = useState([]);
  const [projects, setProjects] = useState([]);
  const [loading, setLoading] = useState(true);
  const [activeClipModal, setActiveClipModal] = useState(null);
  const [selectedClipIds, setSelectedClipIds] = useState([]);
  const [filterMinScore, setFilterMinScore] = useState(0);

  const fetchData = async () => {
    try {
      const [clipsData, projectsData] = await Promise.all([
        listClips(),
        listProjects()
      ]);
      setClips(clipsData);
      setProjects(projectsData);
    } catch (err) {
      console.error('Failed to load clips library:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchData();
  }, []);

  const handleDeleteClip = async (clipId) => {
    if (!window.confirm('Are you sure you want to delete this clip?')) return;
    try {
      await deleteClip(clipId);
      setClips((prev) => prev.filter((c) => c.id !== clipId));
      if (activeClipModal?.id === clipId) {
        setActiveClipModal(null);
      }
    } catch (err) {
      console.error('Failed to delete clip:', err);
    }
  };

  // Filter clips based on selected project and minimum score
  const filteredClips = clips.filter((c) => {
    if (selectedProjectId && c.project_id !== selectedProjectId) return false;
    if (filterMinScore > 0 && c.highlight_score < filterMinScore) return false;
    return true;
  });

  const handleSelectAll = () => {
    if (selectedClipIds.length === filteredClips.length) {
      setSelectedClipIds([]);
    } else {
      setSelectedClipIds(filteredClips.map((c) => c.id));
    }
  };

  const toggleSelectClip = (id, e) => {
    e.stopPropagation();
    setSelectedClipIds((prev) =>
      prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id]
    );
  };

  const handleDownloadSelected = () => {
    // Triggers download for all selected clips sequentially
    selectedClipIds.forEach((id) => {
      const a = document.createElement('a');
      a.href = getClipDownloadUrl(id);
      a.download = `clip_${id}.mp4`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
    });
  };

  const getScoreBadge = (score) => {
    if (score >= 80) return 'bg-emerald-500/20 text-emerald-400 border-emerald-500/30';
    if (score >= 60) return 'bg-[#747CFF]/20 text-[#9B9EFF] border-[#747CFF]/30';
    return 'bg-amber-500/20 text-amber-400 border-amber-500/30';
  };

  return (
    <div className="max-w-7xl mx-auto space-y-6">
      {/* Top Header & Actions */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h2 className="text-2xl font-bold text-white tracking-tight">Generated Clips</h2>
          <p className="text-sm text-slate-400 mt-1">
            Browse, preview, and download all 9:16 vertical shorts generated by ClipForge AI.
          </p>
        </div>

        {/* Global Toolbar */}
        <div className="flex flex-wrap items-center gap-3">
          {filteredClips.length > 0 && (
            <>
              <button
                onClick={handleSelectAll}
                className="flex items-center gap-1.5 px-3 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-semibold transition cursor-pointer"
              >
                {selectedClipIds.length === filteredClips.length ? (
                  <CheckSquare className="w-4 h-4 text-[#747CFF]" />
                ) : (
                  <Square className="w-4 h-4 text-slate-400" />
                )}
                <span>
                  {selectedClipIds.length === filteredClips.length ? 'Deselect All' : 'Select All'}
                </span>
              </button>

              {selectedClipIds.length > 0 && (
                <button
                  onClick={handleDownloadSelected}
                  className="flex items-center gap-1.5 px-4 py-2 rounded-xl brand-gradient brand-gradient-hover text-white text-xs font-semibold glow-primary shadow transition cursor-pointer"
                >
                  <Download className="w-4 h-4" />
                  <span>Download Selected ({selectedClipIds.length})</span>
                </button>
              )}
            </>
          )}
        </div>
      </div>

      {/* Filter Bar */}
      <div className="p-4 rounded-xl bg-[#131A2B] border border-slate-800 flex flex-wrap items-center gap-4 text-xs">
        <div className="flex items-center gap-2 text-slate-400 font-semibold">
          <Filter className="w-3.5 h-3.5 text-[#747CFF]" />
          <span>Filter:</span>
        </div>

        {/* Project Filter */}
        <div className="flex items-center gap-2">
          <span className="text-slate-400">Project:</span>
          <select
            value={selectedProjectId || ''}
            onChange={(e) => setSelectedProjectId(e.target.value ? parseInt(e.target.value, 10) : null)}
            className="px-3 py-1.5 rounded-lg bg-slate-900 border border-slate-700 text-slate-200 focus:outline-none focus:border-[#747CFF] cursor-pointer"
          >
            <option value="">All Projects ({clips.length} clips)</option>
            {projects.map((p) => (
              <option key={p.id} value={p.id}>
                {p.title}
              </option>
            ))}
          </select>
        </div>

        {/* Highlight Score Filter */}
        <div className="flex items-center gap-2">
          <span className="text-slate-400">Min Score:</span>
          <select
            value={filterMinScore}
            onChange={(e) => setFilterMinScore(parseInt(e.target.value, 10))}
            className="px-3 py-1.5 rounded-lg bg-slate-900 border border-slate-700 text-slate-200 focus:outline-none focus:border-[#747CFF] cursor-pointer"
          >
            <option value="0">All Scores (0+)</option>
            <option value="60">Good Moments (60+)</option>
            <option value="80">Top Highlights (80+)</option>
          </select>
        </div>

        {selectedProjectId && (
          <button
            onClick={() => setSelectedProjectId(null)}
            className="text-xs text-[#9B9EFF] hover:underline cursor-pointer"
          >
            Clear Project Filter
          </button>
        )}
      </div>

      {/* Clips Grid */}
      {loading ? (
        <div className="py-20 flex justify-center">
          <Loader2 className="w-8 h-8 animate-spin text-[#747CFF]" />
        </div>
      ) : filteredClips.length === 0 ? (
        <div className="text-center py-20 bg-[#131A2B] border border-dashed border-slate-800 rounded-2xl">
          <Film className="w-12 h-12 text-slate-600 mx-auto mb-3" />
          <h3 className="text-base font-semibold text-slate-300">No clips found</h3>
          <p className="text-xs text-slate-500 mt-1 max-w-sm mx-auto">
            {selectedProjectId ? 'No clips found for this project filter.' : 'Upload or ingest a video to create your first set of AI clips.'}
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 lg:grid-cols-4 gap-6">
          {filteredClips.map((clip) => {
            const isSelected = selectedClipIds.includes(clip.id);
            return (
              <div
                key={clip.id}
                onClick={() => setActiveClipModal(clip)}
                className={`group rounded-2xl bg-[#131A2B] border transition-all duration-300 overflow-hidden flex flex-col justify-between shadow-lg cursor-pointer hover:border-[#747CFF]/50 ${
                  isSelected ? 'border-[#747CFF] ring-2 ring-[#747CFF]/40' : 'border-slate-800'
                }`}
              >
                {/* 9:16 Aspect Thumbnail Box */}
                <div className="relative aspect-[9/16] bg-black overflow-hidden">
                  {clip.thumbnail_url ? (
                    <img
                      src={resolveMediaUrl(clip.thumbnail_url)}
                      alt={clip.title}
                      className="w-full h-full object-cover group-hover:scale-105 transition-transform duration-300"
                    />
                  ) : (
                    <div className="w-full h-full flex items-center justify-center bg-slate-900">
                      <Film className="w-10 h-10 text-slate-600" />
                    </div>
                  )}

                  {/* Gradient Overlay */}
                  <div className="absolute inset-0 bg-gradient-to-t from-[#131A2B] via-transparent to-black/40 p-3 flex flex-col justify-between">
                    {/* Top Row: Checkbox & Score */}
                    <div className="flex items-center justify-between">
                      <button
                        type="button"
                        onClick={(e) => toggleSelectClip(clip.id, e)}
                        className="p-1 rounded-md bg-black/60 hover:bg-black text-white transition cursor-pointer"
                      >
                        {isSelected ? (
                          <CheckSquare className="w-4 h-4 text-[#747CFF]" />
                        ) : (
                          <Square className="w-4 h-4 text-slate-400" />
                        )}
                      </button>

                      <span className={`px-2 py-0.5 rounded-full text-xs font-bold border ${getScoreBadge(clip.highlight_score)}`}>
                        {clip.highlight_score}
                      </span>
                    </div>

                    {/* Center: Play Icon Glow on Hover */}
                    <div className="self-center w-12 h-12 rounded-full bg-white/20 backdrop-blur-md flex items-center justify-center opacity-0 group-hover:opacity-100 transition duration-300">
                      <Play className="w-5 h-5 text-white fill-white ml-0.5" />
                    </div>

                    {/* Bottom overlay: Clip Number and duration */}
                    <div className="flex items-center justify-between text-xs text-white">
                      <span className="font-bold bg-black/60 px-2 py-0.5 rounded-md">
                        Clip #{clip.clip_number}
                      </span>
                      <span className="flex items-center gap-1 bg-black/60 px-2 py-0.5 rounded-md text-[11px]">
                        <Clock className="w-3 h-3 text-[#747CFF]" />
                        {clip.duration}s
                      </span>
                    </div>
                  </div>
                </div>

                {/* Card Content & Metadata */}
                <div className="p-4 space-y-3">
                  <div>
                    <h4 className="text-sm font-bold text-white line-clamp-1 group-hover:text-[#9B9EFF] transition">
                      {clip.title}
                    </h4>
                    {clip.reasoning && (
                      <p className="text-[11px] text-slate-400 line-clamp-1 mt-0.5 font-medium">
                        {clip.reasoning}
                      </p>
                    )}
                  </div>

                  {clip.transcript && (
                    <p className="text-xs text-slate-400 line-clamp-2 leading-relaxed bg-slate-900/60 p-2 rounded-lg border border-slate-800/80 italic">
                      "{clip.transcript}"
                    </p>
                  )}

                  {/* Actions Bar */}
                  <div className="pt-2 border-t border-slate-800/80 flex items-center justify-between gap-2">
                    <a
                      href={getClipDownloadUrl(clip.id)}
                      download
                      onClick={(e) => e.stopPropagation()}
                      className="flex-1 flex items-center justify-center gap-1.5 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-semibold transition"
                      title="Download MP4"
                    >
                      <Download className="w-3.5 h-3.5" />
                      <span>Download</span>
                    </a>

                    <a
                      href={getSubtitleDownloadUrl(clip.id, 'srt')}
                      download
                      onClick={(e) => e.stopPropagation()}
                      className="p-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white transition"
                      title="Download SRT Subtitle"
                    >
                      <FileText className="w-3.5 h-3.5" />
                    </a>

                    <button
                      type="button"
                      onClick={(e) => {
                        e.stopPropagation();
                        handleDeleteClip(clip.id);
                      }}
                      className="p-1.5 rounded-lg bg-red-500/10 hover:bg-red-500/20 text-red-400 transition"
                      title="Delete Clip"
                    >
                      <Trash2 className="w-3.5 h-3.5" />
                    </button>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}

      {/* Video Player Modal */}
      {activeClipModal && (
        <ClipPlayerModal
          clip={activeClipModal}
          onClose={() => setActiveClipModal(null)}
          onDelete={handleDeleteClip}
        />
      )}
    </div>
  );
}
